function setupNavigation() {
  const nav = document.getElementById("mainNav");
  const toggler = document.querySelector(".navbar-toggler");
  const hasBootstrap = window.bootstrap && bootstrap.Collapse;
  const collapse = hasBootstrap ? bootstrap.Collapse.getOrCreateInstance(nav, { toggle: false }) : null;

  toggler.addEventListener("click", () => {
    if (hasBootstrap) return;
    const isOpen = nav.classList.toggle("show");
    toggler.setAttribute("aria-expanded", String(isOpen));
  });

  nav.querySelectorAll("a[href^='#']").forEach((link) => {
    link.addEventListener("click", () => {
      if (!nav.classList.contains("show")) return;
      if (hasBootstrap) {
        collapse.hide();
      } else {
        nav.classList.remove("show");
        toggler.setAttribute("aria-expanded", "false");
      }
    });
  });
}

function setupLinks() {
  document.querySelectorAll("[data-instagram-link]").forEach((link) => {
    link.href = SITE_CONFIG.instagramUrl;
  });

  document.addEventListener("click", (event) => {
    const link = event.target.closest("[data-whatsapp-service]");
    if (!link) return;
    event.preventDefault();

    const serviceName = link.dataset.whatsappService;
    const url = makeWhatsAppUrl(directEnquiryMessage(serviceName));
    if (!url) {
      alert("WhatsApp number is not configured yet.");
      return;
    }
    window.open(url, "_blank", "noopener");
  });
}

function setupBookingForm() {
  const form = document.getElementById("bookingForm");
  const status = document.getElementById("formStatus");

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    status.classList.remove("show");

    if (!SITE_CONFIG.whatsappNumber) {
      showStatus("WhatsApp number is missing. Please update SITE_CONFIG.whatsappNumber in js/script.js before using the booking form.");
      return;
    }

    if (!form.checkValidity()) {
      form.classList.add("was-validated");
      return;
    }

    const data = new FormData(form);
    const emailLine = data.get("email") ? `Email: ${data.get("email")}\n` : "";
    const detailsLine = data.get("details") ? data.get("details") : "Not shared";
    const message = `Hello Anuj,\n\nI would like to enquire about your makeup services.\n\nName: ${data.get("fullName")}\nContact Number: ${data.get("phone")}\n${emailLine}Service: ${data.get("service")}\nEvent Date: ${data.get("eventDate")}\nEvent Location: ${data.get("eventLocation")}\nAdditional Details: ${detailsLine}\n\nPlease share your availability and pricing.\n\nThank you.`;

    showStatus("WhatsApp is opening with your enquiry details. Please review and send the message there to complete your enquiry.");
    window.open(makeWhatsAppUrl(message), "_blank", "noopener");
  });

  function showStatus(message) {
    status.textContent = message;
    status.classList.add("show");
  }
}

function setupLightbox() {
  const grid = document.getElementById("portfolioGrid");
  const lightbox = document.getElementById("lightbox");
  const image = lightbox.querySelector("img");
  const caption = lightbox.querySelector("figcaption");
  const closeButton = lightbox.querySelector(".lightbox-close");
  const prevButton = lightbox.querySelector(".lightbox-prev");
  const nextButton = lightbox.querySelector(".lightbox-next");

  grid.addEventListener("click", (event) => {
    const item = event.target.closest(".portfolio-item");
    if (!item) return;
    openLightbox(Number(item.dataset.index), item);
  });

  closeButton.addEventListener("click", closeLightbox);
  prevButton.addEventListener("click", () => moveLightbox(-1));
  nextButton.addEventListener("click", () => moveLightbox(1));
  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) closeLightbox();
  });

  document.addEventListener("keydown", (event) => {
    if (!lightbox.classList.contains("active")) return;
    if (event.key === "Escape") closeLightbox();
    if (event.key === "ArrowLeft") moveLightbox(-1);
    if (event.key === "ArrowRight") moveLightbox(1);
    if (event.key === "Tab") trapFocus(event);
  });

  function openLightbox(index, trigger) {
    lastFocusedElement = trigger;
    activeLightboxIndex = index;
    updateLightbox();
    lightbox.classList.add("active");
    lightbox.setAttribute("aria-hidden", "false");
    document.body.classList.add("lightbox-open");
    closeButton.focus();
  }

  function closeLightbox() {
    lightbox.classList.remove("active");
    lightbox.setAttribute("aria-hidden", "true");
    document.body.classList.remove("lightbox-open");
    if (lastFocusedElement) lastFocusedElement.focus();
  }

  function moveLightbox(direction) {
    activeLightboxIndex = (activeLightboxIndex + direction + visibleItems.length) % visibleItems.length;
    updateLightbox();
  }

  function updateLightbox() {
    const item = visibleItems[activeLightboxIndex];
    image.src = item.image;
    image.alt = item.alt;
    caption.textContent = `${item.title} — ${item.caption}`;
  }

  function trapFocus(event) {
    const focusables = [closeButton, prevButton, nextButton];
    const currentIndex = focusables.indexOf(document.activeElement);
    if (event.shiftKey && currentIndex === 0) {
      event.preventDefault();
      focusables[focusables.length - 1].focus();
    } else if (!event.shiftKey && currentIndex === focusables.length - 1) {
      event.preventDefault();
      focusables[0].focus();
    }
  }
}

function applyConfigToggles() {
  const promo = document.getElementById("promoBanner");
  const testimonials = document.getElementById("testimonials");
  promo.classList.toggle("d-none", !SITE_CONFIG.promotionVisible);
  testimonials.classList.toggle("d-none", !SITE_CONFIG.testimonialsVisible);
}
