function renderFilters() {
  const filterBar = document.querySelector(".filter-bar");
  filterBar.innerHTML = categories.map((category) => `
    <button class="filter-btn${category === activeCategory ? " active" : ""}" type="button" role="tab" aria-selected="${category === activeCategory}" data-category="${category}">
      ${category}
    </button>
  `).join("");

  filterBar.addEventListener("click", (event) => {
    const button = event.target.closest("[data-category]");
    if (!button) return;
    activeCategory = button.dataset.category;
    renderFilters();
    renderPortfolio();
  }, { once: true });
}

function renderPortfolio() {
  visibleItems = activeCategory === "All Looks"
    ? [...SITE_CONFIG.portfolio]
    : SITE_CONFIG.portfolio.filter((item) => item.category === activeCategory);

  const grid = document.getElementById("portfolioGrid");
  if (!visibleItems.length) {
    grid.innerHTML = `<p class="text-center">No images are available for this category yet. Add original portfolio photos in the JavaScript gallery array.</p>`;
    return;
  }

  grid.innerHTML = visibleItems.map((item, index) => `
    <button class="portfolio-item" type="button" data-index="${index}" aria-label="Open ${item.title}">
      <figure>
        <img src="${item.image}" alt="${item.alt}" loading="lazy" width="900" height="1200">
        <figcaption><span>${item.category}</span><strong>${item.title}</strong></figcaption>
      </figure>
    </button>
  `).join("");
}

